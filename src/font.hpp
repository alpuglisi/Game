inline int textWidth(const std::string& s, int scale) { return (int)s.size() * 6 * scale; }

inline void draw(SDL_Renderer* r, const std::string& s, int x, int y, int scale, SDL_Color c) {
    SDL_SetRenderDrawColor(r, c.r, c.g, c.b, c.a);
    for (char ch : s) {
        if (const uint8_t* g = glyph(ch)) {
            for (int row = 0; row < 7; ++row) {
                for (int col = 0; col < 5; ++col) {
                    if (g[row] & (0x10 >> col)) {
                        SDL_Rect rc{x + col * scale, y + row * scale, scale, scale};
                        SDL_RenderFillRect(r, &rc);
                    }
                }
            }
        }
        x += 6 * scale;
    }
}

